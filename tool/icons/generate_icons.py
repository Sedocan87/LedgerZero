#!/usr/bin/env python3
"""Generates every LedgerZero icon from one geometry.

The mark: a "0" (straight sides, round ends) with three ledger lines in it, white on a teal
gradient (the app's seed colour). Outputs:

  Android (android/app/src/main/res)
    drawable/ic_launcher_background.xml   adaptive icon background (vector)
    drawable/ic_launcher_foreground.xml   adaptive icon foreground (vector)
    drawable/ic_launcher_monochrome.xml   themed icon, Android 13+ (vector)
    drawable/ic_stat_ledgerzero.xml       status-bar notification icon
    drawable/launch_logo.xml              the mark for the launch screen
    mipmap-anydpi-v26/ic_launcher(_round).xml
    mipmap-*/ic_launcher.png, ic_launcher_round.png   Android 7.0-7.1
  Store (store/)
    play_icon_512.png        Play Console app icon (512 x 512, no alpha)
    feature_graphic.png      Play Console feature graphic (1024 x 500)
    icon_preview.png         all variants side by side, for review

Needs Python 3 with Pillow (pip install pillow). Run from the repository
root:  python3 tool/icons/generate_icons.py
"""

import math
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
RES = os.path.join(ROOT, "android", "app", "src", "main", "res")
STORE = os.path.join(ROOT, "store")
INTER_BOLD = os.path.join(ROOT, "assets", "fonts", "Inter", "Inter-Bold.ttf")
INTER_MEDIUM = os.path.join(ROOT, "assets", "fonts", "Inter", "Inter-Medium.ttf")

# Teal gradient around the app's seed colour (#009688), top left to bottom
# right.
GRADIENT_START = (0x00, 0xA8, 0x96)
GRADIENT_END = (0x00, 0x5F, 0x56)
WHITE = (255, 255, 255)


# ---------------------------------------------------------------------------
# Geometry
# ---------------------------------------------------------------------------


class Mark:
    """The mark on a square canvas of [size] units: a ring and three bars."""

    def __init__(self, size, cx, cy, rx, ry, stroke, bar, gap, halves):
        self.size = size
        self.cx, self.cy = cx, cy
        self.rx, self.ry = rx, ry
        self.irx, self.iry = rx - stroke, ry - stroke
        self.bar = bar  # bar thickness
        # Bars: (centre y, half length including the round caps).
        self.bars = [
            (cy - gap, halves[0]),
            (cy, halves[1]),
            (cy + gap, halves[2]),
        ]


# Adaptive icon: 108 x 108 dp, the safe zone is the circle of 66 dp in the
# middle; the mark stays well inside it.
ADAPTIVE = Mark(108, 54, 54, 17.5, 24, 6.6, 3.6, 7.0, (4.6, 7.0, 4.6))

# Notification icon: 24 x 24 dp, white silhouette only.
STATUS = Mark(24, 12, 12, 7.4, 10.4, 2.6, 1.7, 3.1, (2.0, 3.0, 2.0))


def fmt(v):
    return ("%.2f" % v).rstrip("0").rstrip(".")


def stadium_path(cx, cy, rx, ry):
    """A "0" as typefaces draw it: straight sides, round ends (a rounded
    rectangle whose corner radius is half its width)."""
    r = rx
    straight = 2 * ry - 2 * r
    return (
        f"M{fmt(cx - rx)},{fmt(cy - ry + r)} "
        f"a{fmt(r)},{fmt(r)} 0 0,1 {fmt(2 * r)},0 "
        f"v{fmt(straight)} "
        f"a{fmt(r)},{fmt(r)} 0 0,1 {fmt(-2 * r)},0 z"
    )


def capsule_path(cx, cy, half, thickness):
    r = thickness / 2
    straight = 2 * half - 2 * r
    return (
        f"M{fmt(cx - half + r)},{fmt(cy - r)} "
        f"h{fmt(straight)} "
        f"a{fmt(r)},{fmt(r)} 0 0,1 0,{fmt(2 * r)} "
        f"h{fmt(-straight)} "
        f"a{fmt(r)},{fmt(r)} 0 0,1 0,{fmt(-2 * r)} z"
    )


def ring_path(m):
    return stadium_path(m.cx, m.cy, m.rx, m.ry) + " " + stadium_path(
        m.cx, m.cy, m.irx, m.iry
    )


def bars_path(m):
    return " ".join(capsule_path(m.cx, y, h, m.bar) for y, h in m.bars)


# ---------------------------------------------------------------------------
# Vector drawables
# ---------------------------------------------------------------------------


def vector(m, body, extra_ns=""):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/icons/generate_icons.py; edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"{extra_ns}
    android:width="{m.size}dp"
    android:height="{m.size}dp"
    android:viewportWidth="{m.size}"
    android:viewportHeight="{m.size}">
{body}
</vector>
"""


def mark_paths(m, color):
    return f"""    <path
        android:fillColor="{color}"
        android:fillType="evenOdd"
        android:pathData="{ring_path(m)}" />
    <path
        android:fillColor="{color}"
        android:pathData="{bars_path(m)}" />"""


def hex_rgb(c):
    return "#FF%02X%02X%02X" % c


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def write_vectors():
    background = vector(
        ADAPTIVE,
        f"""    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="0"
                android:startY="0"
                android:endX="108"
                android:endY="108"
                android:startColor="{hex_rgb(GRADIENT_START)}"
                android:endColor="{hex_rgb(GRADIENT_END)}" />
        </aapt:attr>
    </path>""",
        extra_ns='\n    xmlns:aapt="http://schemas.android.com/aapt"',
    )
    write(os.path.join(RES, "drawable", "ic_launcher_background.xml"), background)
    write(
        os.path.join(RES, "drawable", "ic_launcher_foreground.xml"),
        vector(ADAPTIVE, mark_paths(ADAPTIVE, "#FFFFFFFF")),
    )
    # Themed icons: Android tints the silhouette itself.
    write(
        os.path.join(RES, "drawable", "ic_launcher_monochrome.xml"),
        vector(ADAPTIVE, mark_paths(ADAPTIVE, "#FFFFFFFF")),
    )
    # Status bar: white on transparent (Android draws it in the system
    # colour).
    write(
        os.path.join(RES, "drawable", "ic_stat_ledgerzero.xml"),
        vector(STATUS, mark_paths(STATUS, "#FFFFFFFF")),
    )
    # Launch screen (before Android 12): the mark in the brand colour on the
    # window background.
    write(
        os.path.join(RES, "drawable", "launch_logo.xml"),
        vector(ADAPTIVE, mark_paths(ADAPTIVE, hex_rgb(GRADIENT_END))),
    )
    adaptive = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/icons/generate_icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
"""
    for name in ("ic_launcher", "ic_launcher_round"):
        write(os.path.join(RES, "mipmap-anydpi-v26", f"{name}.xml"), adaptive)


# ---------------------------------------------------------------------------
# Raster images
# ---------------------------------------------------------------------------

SS = 4  # supersampling factor


def gradient(w, h):
    img = Image.new("RGB", (w, h))
    px = img.load()
    total = w + h - 2 or 1
    for y in range(h):
        for x in range(w):
            t = (x + y) / total
            px[x, y] = tuple(
                round(a + (b - a) * t) for a, b in zip(GRADIENT_START, GRADIENT_END)
            )
    return img


def mark_mask(m, px, scale=1.0, offset=(0, 0)):
    """A supersampled L mask of the mark, [px] pixels square for the mark's
    canvas, scaled by [scale] around its centre and moved by [offset]."""
    big = px * SS
    mask = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(mask)
    u = big / m.size * scale
    ox = big / 2 - m.cx * u + offset[0] * SS
    oy = big / 2 - m.cy * u + offset[1] * SS

    def box(cx, cy, rx, ry):
        return [ox + (cx - rx) * u, oy + (cy - ry) * u, ox + (cx + rx) * u, oy + (cy + ry) * u]

    d.rounded_rectangle(box(m.cx, m.cy, m.rx, m.ry), radius=m.rx * u, fill=255)
    d.rounded_rectangle(box(m.cx, m.cy, m.irx, m.iry), radius=m.irx * u, fill=0)
    r = m.bar / 2 * u
    for y, h in m.bars:
        d.rounded_rectangle(
            [ox + (m.cx - h) * u, oy + y * u - r, ox + (m.cx + h) * u, oy + y * u + r],
            radius=r,
            fill=255,
        )
    return mask.resize((px, px), Image.LANCZOS)


def tile(px, shape):
    """The full icon: gradient, white mark, clipped to [shape]."""
    bg = gradient(px, px).convert("RGBA")
    white = Image.new("RGBA", (px, px), WHITE + (255,))
    # The legacy icon has no safe-zone margin to lose: the mark a bit larger.
    bg.paste(white, (0, 0), mark_mask(ADAPTIVE, px, scale=1.25))
    clip = Image.new("L", (px * SS, px * SS), 0)
    d = ImageDraw.Draw(clip)
    if shape == "circle":
        d.ellipse([0, 0, px * SS - 1, px * SS - 1], fill=255)
    elif shape == "rounded":
        d.rounded_rectangle([0, 0, px * SS - 1, px * SS - 1], radius=px * SS * 0.22, fill=255)
    else:
        d.rectangle([0, 0, px * SS, px * SS], fill=255)
    clip = clip.resize((px, px), Image.LANCZOS)
    out = Image.new("RGBA", (px, px), (0, 0, 0, 0))
    out.paste(bg, (0, 0), clip)
    return out


DENSITIES = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}


def write_legacy_pngs():
    for density, px in DENSITIES.items():
        folder = os.path.join(RES, f"mipmap-{density}")
        os.makedirs(folder, exist_ok=True)
        tile(px, "rounded").save(os.path.join(folder, "ic_launcher.png"))
        tile(px, "circle").save(os.path.join(folder, "ic_launcher_round.png"))


def write_store():
    os.makedirs(STORE, exist_ok=True)
    # Play icon: full square, Play applies its own mask; the mark at the
    # adaptive icon's proportions, a little larger.
    icon = gradient(512, 512).convert("RGBA")
    icon.paste(
        Image.new("RGBA", (512, 512), WHITE + (255,)),
        (0, 0),
        mark_mask(ADAPTIVE, 512, scale=1.15),
    )
    icon.convert("RGB").save(os.path.join(STORE, "play_icon_512.png"))

    # Feature graphic: the icon tile on the left, name and line on the right.
    fg = gradient(1024, 500).convert("RGBA")
    mark = mark_mask(ADAPTIVE, 420, scale=1.35)
    fg.paste(Image.new("RGBA", (420, 420), WHITE + (255,)), (60, 40), mark)
    d = ImageDraw.Draw(fg)
    title = ImageFont.truetype(INTER_BOLD, 92)
    line = ImageFont.truetype(INTER_MEDIUM, 38)
    d.text((470, 160), "LedgerZero", font=title, fill=WHITE)
    d.text((474, 285), "Envelope budgeting", font=line, fill=(225, 245, 242))
    d.text((474, 338), "Offline. No account. Pay once.", font=line, fill=(225, 245, 242))
    fg.convert("RGB").save(os.path.join(STORE, "feature_graphic.png"))


def write_preview():
    """Launcher shapes, themed icon, notification icon at several sizes, on
    light and dark backgrounds."""
    w, h = 1000, 420
    out = Image.new("RGB", (w, h), (245, 245, 245))
    out.paste((30, 30, 30), [0, h // 2, w, h])
    x = 20
    for shape in ("circle", "rounded", "square"):
        t = tile(160, shape)
        out.paste(t, (x, 20), t)
        out.paste(t, (x, 230), t)
        x += 180
    # Themed (monochrome) icon as Android 13 draws it.
    mono_bg = Image.new("RGBA", (160, 160), (0, 0, 0, 0))
    ImageDraw.Draw(mono_bg).ellipse([0, 0, 159, 159], fill=(203, 230, 225, 255))
    mono_bg.paste(
        Image.new("RGBA", (160, 160), (0, 77, 64, 255)), (0, 0), mark_mask(ADAPTIVE, 160)
    )
    out.paste(mono_bg, (x, 20), mono_bg)
    x += 180
    # Notification icon: 24, 36, 48, 72 px.
    for px in (24, 36, 48, 72):
        m = mark_mask(STATUS, px)
        out.paste((60, 60, 60), (x, 60, x + px, 60 + px), m)
        out.paste((240, 240, 240), (x, 270, x + px, 270 + px), m)
        x += px + 14
    out.save(os.path.join(STORE, "icon_preview.png"))


def main():
    if not os.path.exists(INTER_BOLD):
        sys.exit("Inter fonts not found; run from the repository root.")
    write_vectors()
    write_legacy_pngs()
    write_store()
    write_preview()
    print("Icons written to android/app/src/main/res and store/.")


if __name__ == "__main__":
    main()
